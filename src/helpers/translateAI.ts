type TranslationMessage = { role: 'system' | 'user'; content: string };

export type OpenAICompatibleTranslationConfig = {
  baseUrl: string;
  apiKey?: string;
  model: string;
  /* Extra fields merged into the request body, e.g. provider-specific reasoning toggles */
  extraBody?: Record<string, unknown>;
};

const buildTranslationMessages = (
  text: string,
  sourceLang: string,
  targetLang: string
): TranslationMessage[] => [
  {
    role: 'system',
    content: `You are a translation assistant. You will be given text from a social media post and you will need to translate it to the target language as accurately as possible.
Do not include any other text in your response.
Do not introduce new information not present in the original text.
Hashtags, usernames, and similar content should be kept in the original language.
Maintain the original text's emojis, punctuation, whitespaces, and line breaks.

The source language is ${i18next.t(`language_${sourceLang}`, { lng: 'en' })}.
The target language is ${i18next.t(`language_${targetLang}`, { lng: 'en' })}.`
  },
  {
    role: 'user',
    content: `${text}`
  }
];

/* Remove reasoning framing after literal source markers have been protected.
   A closing marker alone is not sufficient evidence of reasoning. */
export const stripReasoning = (text: string): string => {
  let cursor = 0;
  let result = '';
  let trimLeading = false;
  while (true) {
    const start = text.indexOf('<think>', cursor);
    if (start === -1) {
      result += text.slice(cursor);
      return trimLeading ? result.trimStart() : result;
    }
    const end = text.indexOf('</think>', start + '<think>'.length);
    if (end === -1) return '';
    if (cursor === 0 && !text.slice(0, start).trim()) trimLeading = true;
    result += text.slice(cursor, start);
    cursor = end + '</think>'.length;
  }
};

type ProtectedLiteralText = {
  text: string;
  prefix: string;
  markers: { token: string; value: string }[];
};

// Source markup must not be confused with reasoning generated by the model.
const protectLiteralThinkTags = (text: string): ProtectedLiteralText | null => {
  const occurrences: { start: number; value: string }[] = [];
  let searchFrom = 0;
  while (true) {
    const start = text.indexOf('<', searchFrom);
    if (start === -1) break;
    const opening = text.slice(start, start + '<think>'.length);
    const closing = text.slice(start, start + '</think>'.length);
    const value =
      opening.toLowerCase() === '<think>'
        ? opening
        : closing.toLowerCase() === '</think>'
          ? closing
          : '';
    if (value) occurrences.push({ start, value });
    searchFrom = start + (value ? value.length : 1);
  }
  if (!occurrences.length) return { text, prefix: '', markers: [] };
  const prefix = '__FX_LITERAL_' + crypto.randomUUID() + '_';
  if (text.includes(prefix)) return null;
  const markers: ProtectedLiteralText['markers'] = [];
  const parts: string[] = [];
  let cursor = 0;
  for (const { start, value } of occurrences) {
    const token = prefix + markers.length + '__';
    markers.push({ token, value });
    parts.push(text.slice(cursor, start), token);
    cursor = start + value.length;
  }
  parts.push(text.slice(cursor));
  return { text: parts.join(''), prefix, markers };
};

const restoreLiteralThinkTags = (text: string, input: ProtectedLiteralText): string | null => {
  if (!input.markers.length) return text;
  const parts: string[] = [];
  let cursor = 0;
  for (const { token, value } of input.markers) {
    const position = text.indexOf(input.prefix, cursor);
    if (position === -1 || !text.startsWith(token, position)) return null;
    parts.push(text.slice(cursor, position), value);
    cursor = position + token.length;
  }
  if (text.includes(input.prefix, cursor)) return null;
  parts.push(text.slice(cursor));
  return parts.join('');
};

const parseExtraBody = (raw: string): Record<string, unknown> | undefined => {
  if (!raw) {
    return undefined;
  }
  try {
    const parsed: unknown = JSON.parse(raw);
    if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
      return parsed as Record<string, unknown>;
    }
  } catch (e: unknown) {
    console.error('LLM_TRANSLATION_EXTRA_BODY is not valid JSON', e);
    return undefined;
  }
  console.error('LLM_TRANSLATION_EXTRA_BODY must be a JSON object');
  return undefined;
};

const getOpenAICompatibleTranslationConfig = (
  c?: Context
): OpenAICompatibleTranslationConfig | null => {
  const runtime = c?.env ?? {};
  const baseUrl = runtime.LLM_TRANSLATION_BASE_URL ?? Constants.LLM_TRANSLATION_BASE_URL;
  const model = runtime.LLM_TRANSLATION_MODEL ?? Constants.LLM_TRANSLATION_MODEL;
  if (!baseUrl || !model) {
    return null;
  }
  return {
    baseUrl,
    apiKey: runtime.LLM_TRANSLATION_API_KEY ?? Constants.LLM_TRANSLATION_API_KEY,
    model,
    extraBody: parseExtraBody(
      runtime.LLM_TRANSLATION_EXTRA_BODY ?? Constants.LLM_TRANSLATION_EXTRA_BODY
    )
  };
};

/* Whether any LLM translation backend (Workers AI binding or OpenAI-compatible endpoint) is usable */
export const isAITranslationAvailable = (c: Context): boolean =>
  Boolean(c.env?.AI) || getOpenAICompatibleTranslationConfig(c) !== null;

/* Translates text using any OpenAI-compatible chat completions endpoint */
export const translateTextOpenAICompatible = async (
  text: string,
  sourceLang: string,
  targetLang: string,
  config: OpenAICompatibleTranslationConfig
): Promise<CFAITranslation | null> => {
  const headers: Record<string, string> = {
    'Content-Type': 'application/json',
    'User-Agent': Constants.FRIENDLY_USER_AGENT
  };
  if (config.apiKey) {
    headers['Authorization'] = `Bearer ${config.apiKey}`;
  }

  const endpoint = new URL(`${config.baseUrl.replace(/\/+$/, '')}/chat/completions`);
  if (
    !['http:', 'https:'].includes(endpoint.protocol) ||
    (config.apiKey && endpoint.protocol !== 'https:')
  ) {
    throw new Error('Translation endpoints with an API key require HTTPS');
  }
  const protectedInput = protectLiteralThinkTags(text);
  if (!protectedInput) return null;
  const messages = buildTranslationMessages(protectedInput.text, sourceLang, targetLang).map(
    message =>
      message.role === 'system' && protectedInput.markers.length
        ? {
            ...message,
            content:
              message.content +
              '\nPreserve each literal-source placeholder beginning with ' +
              protectedInput.prefix +
              ' exactly once, unchanged and in the same order. Do not expand placeholders into markup.'
          }
        : message
  );
  const controller = new AbortController();
  const deadline = setTimeout(() => controller.abort(), 10_000);
  try {
    const response = await fetch(endpoint.toString(), {
      signal: controller.signal,
      redirect: 'manual',
      method: 'POST',
      headers,
      body: JSON.stringify({
        ...config.extraBody,
        model: config.model,
        messages,
        stream: false
      })
    });

    if (!response.ok) {
      console.error(
        'OpenAI-compatible translation failed',
        response.status,
        await response.text().catch(() => '')
      );
      return null;
    }

    const data = (await response.json()) as {
      choices?: { message?: { content?: string | null }; finish_reason?: string | null }[];
      usage?: { prompt_tokens?: number; completion_tokens?: number; total_tokens?: number };
    };
    const choice = data.choices?.[0];
    if (choice?.finish_reason && choice.finish_reason !== 'stop') return null;
    const content = choice?.message?.content;
    if (typeof content !== 'string') {
      console.error('OpenAI-compatible translation returned no content', data);
      return null;
    }
    const translatedText = restoreLiteralThinkTags(stripReasoning(content), protectedInput);
    if (translatedText === null || !translatedText.trim()) {
      return null;
    }

    return {
      translated_text: translatedText,
      usage: {
        prompt_tokens: data.usage?.prompt_tokens ?? 0,
        completion_tokens: data.usage?.completion_tokens ?? 0,
        total_tokens: data.usage?.total_tokens ?? 0
      }
    };
  } finally {
    clearTimeout(deadline);
  }
};

const translateTextLLM = async (
  text: string,
  sourceLang: string,
  targetLang: string,
  c: Context
): Promise<CFAITranslation | null> => {
  const messages = buildTranslationMessages(text, sourceLang, targetLang);
  console.log('messages', messages);
  const response = await c.env.AI.run('@cf/openai/gpt-oss-120b', { messages });
  console.log(`translationResults`, response);
  return {
    translated_text: response.response,
    usage: {
      prompt_tokens: response.usage.prompt_tokens,
      completion_tokens: response.usage.completion_tokens,
      total_tokens: response.usage.total_tokens
    }
  };
};

/* Handles translating statuses when asked! */
export const translateStatusAI = async (
  status: APITwitterStatus | APIBlueskyStatus | APIMastodonStatus | APIStatus,
  _language: string,
  c: Context
): Promise<CFAITranslation | null> => {
  const language = normalizeLanguage(_language);

  const openAIConfig = getOpenAICompatibleTranslationConfig(c);
  if (openAIConfig) {
    console.log('Using OpenAI-compatible LLM translation');

    try {
      const response = await translateTextOpenAICompatible(
        status.text ?? 'Unknown',
        status.lang ?? 'Unknown',
        language,
        openAIConfig
      );
      if (response) {
        return response;
      }
    } catch (e: unknown) {
      console.error('Unknown error while fetching from OpenAI-compatible Translation API', e);
    }
  }

  if (!c.env?.AI) {
    return null;
  }

  console.log('Using LLM translation');

  try {
    const response = await translateTextLLM(
      status.text ?? 'Unknown',
      status.lang ?? 'Unknown',
      language,
      c
    );
    return response;
  } catch (e: unknown) {
    console.error('Unknown error while fetching from Translation API', e);
  }

  console.log('Using M2M100-1.2B translation');

  try {
    const response: CFAITranslation = await c.env.AI.run('@cf/meta/m2m100-1.2b', {
      text: status.text,
      source_lang: status.lang,
      target_lang: language
    });

    console.log(`translationResults`, response);
    return response;
  } catch (e: unknown) {
    console.error('Unknown error while fetching from Translation API', e);
    return null;
  }
};
